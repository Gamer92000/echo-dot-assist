#!/usr/bin/env python3
"""geo/borders.bin into a C file for geo.c: tools/geo/embed.py out.c geo/borders.bin (the zlib'd bytes as they are,
and the size they inflate to)"""
import sys, zlib
out, src = sys.argv[1], sys.argv[2]
data = open(src, "rb").read(); raw = len(zlib.decompress(data))
lines = ["/* generated by tools/geo/embed.py from geo/borders.bin: do not edit */",
         f"const unsigned geo_borders_len = {len(data)}, geo_borders_raw = {raw};",
         f"const unsigned char geo_borders[{len(data)}] = {{"]
for k in range(0, len(data), 24): lines.append("    " + ",".join(str(b) for b in data[k:k + 24]) + ",")
lines.append("};")
open(out, "w").write("\n".join(lines) + "\n")
